async function seed() {
  try {
    await HeroSlide.sync();

    const existingCount = await HeroSlide.count();

    if (existingCount > 0) {
      console.log(
        "⚠️  فيه سلايدات موجودة بالفعل في الجدول (" +
          existingCount +
          "). السكريبت اتوقف عشان منكررش البيانات."
      );
      console.log(
        "لو عايز تضيف السلايدات الستة برضه، امسح كل السلايدات الحالية من لوحة التحكم وشغّل السكريبت تاني."
      );
      process.exit(0);
    }

    for (const item of heroData) {
      const slide = await HeroSlide.create({
        ...item,
        image: "",
        videoThumbnail: "",
        videoUrl: "",
      });
      console.log("✅ اتضاف:", item.title.split("\n")[0], "| id =", slide.id);
    }

    console.log("");
    console.log("✅ تم إضافة الـ 6 سلايدات بنجاح!");
    console.log(
      "افتح لوحة التحكم دلوقتي → السلايدر الرئيسي → هتلاقيهم موجودين، وعدّل على كل واحد وارفعله صورة الخلفية وصورة الفيديو الخاصة بيه."
    );

    process.exit(0);
  } catch (err) {
    console.error("❌ حصل خطأ أثناء إضافة السلايدات:", err);
    process.exit(1);
  }
}

seed();